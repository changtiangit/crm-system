USE crm;

CREATE TABLE IF NOT EXISTS crm_module_records (
  id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  module_name VARCHAR(40) NOT NULL,
  owner VARCHAR(80) NOT NULL DEFAULT '',
  scope_owner VARCHAR(80) NOT NULL DEFAULT '',
  payload JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_module_owner (module_name, scope_owner)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS crm_module_seed_state (
  module_name VARCHAR(40) NOT NULL PRIMARY KEY,
  seeded_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
