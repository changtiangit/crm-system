-- ============================================================
-- 商品（产品）模块初始化脚本
-- 适用于：汽修 / 洗车小件耗材、工贸一体小件耗材
-- 可重复执行：建表用 IF NOT EXISTS，数据用 INSERT IGNORE（商品编码唯一）
-- ============================================================
USE crm;

CREATE TABLE IF NOT EXISTS products (
  id             BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  code           VARCHAR(32)  NOT NULL COMMENT '商品编码',
  name           VARCHAR(100) NOT NULL COMMENT '商品名称',
  category       VARCHAR(50)  NOT NULL COMMENT '商品分类',
  spec           VARCHAR(100)     NULL COMMENT '规格型号',
  unit           VARCHAR(16)  NOT NULL DEFAULT '个' COMMENT '单位',
  purchase_price DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '参考进价',
  sale_price     DECIMAL(10,2) NOT NULL DEFAULT 0 COMMENT '销售价',
  stock          INT          NOT NULL DEFAULT 0 COMMENT '库存数量',
  status         TINYINT      NOT NULL DEFAULT 1 COMMENT '1启用 0停用',
  remark         VARCHAR(255)     NULL COMMENT '备注',
  created_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at     DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_product_code (code),
  KEY idx_product_category (category),
  KEY idx_product_name (name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='商品资料';

