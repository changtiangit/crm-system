-- 商品管理员：四个功能全给
INSERT IGNORE INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code IN
  ('product:view','product:add','product:edit','product:delete')
WHERE r.code = 'PRODUCT_ADMIN';

-- 销售（含两个小组）：只能查看商品，用于报价与下单
INSERT IGNORE INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'product:view'
WHERE r.code IN ('SALES','SALES_G1','SALES_G2');

-- 营销 / 售后 / 技术：只读，便于对外报价与售后备件查询
INSERT IGNORE INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'product:view'
WHERE r.code IN ('MARKET','SERVICE','TECH');
