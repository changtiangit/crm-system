LEFT JOIN crm_order_items i ON i.order_no = t.order_no AND i.product = t.product
WHERE i.id IS NULL;

-- ---------- 回填金额：让每张订单的 amount 与明细合计严格一致 ----------
UPDATE crm_orders o
JOIN (SELECT order_no, SUM(amount) total FROM crm_order_items GROUP BY order_no) s ON s.order_no = o.order_no
SET o.amount = s.total
WHERE o.amount <> s.total;

